"""calibrate.out -> calib_params.sh: the calibrated values every Part 3 script reads, as bash.

Usage: python make_params.py <calib/MODEL_ID dir>   (submit_calibrate.sh runs it after calibrate.py)
Reads <dir>/calibrate.out and writes <dir>/calib_params.sh with
  Q_RC Q_THR Q_NMIN    the criterion: the --choose line if calibrate.py was given one, else its best line
  Q_VARS / Q_ARGS      the same as LAMMPS -var options / recryst_summary.py options
  NUC[T]               suggested --nucleated-size at T for that criterion (2 x the largest glass cluster)
  XC_<cell>[T]         crystal-reference xfracGST at T per composition (no entry for x10: no crystal reference)
  GLASS_<cell>[T]      amorphous-reference xfracGST at T per composition (the glass baseline)
  CALIB_TS             the calibrated temperatures
Every value is copied from calibrate.out, nothing is computed here; a missing section is an error, so a stale or
partial calibrate.out cannot produce a half-filled file.
"""
import re
import sys
from collections import defaultdict
from pathlib import Path


def main():
    d = Path(sys.argv[1]).resolve()
    text = (d / "calibrate.out").read_text()
    m = re.search(r"^chosen \(--choose\): q_rc (\S+)\s+q_thr (\S+)\s+q_nmin (\S+)", text, re.M) \
        or re.search(r"^best: q_rc (\S+)\s+q_thr (\S+)\s+q_nmin (\S+)", text, re.M)
    if not m:
        sys.exit(f"{d}/calibrate.out: no 'chosen' or 'best' criterion line")
    rc, thr, nmin = m.groups()
    chosen = m[0].startswith("chosen")

    xc, glass = defaultdict(dict), defaultdict(dict)
    for kind, cell, T, x in re.findall(r"^\s+(crystal|amorphous)\s+(?:crys|amor)_(\w+?)_(\d+)K\.lammpstrj\.gz\s+"
                                       r"xfracGST ([\d.]+)", text, re.M):
        (xc if kind == "crystal" else glass)[cell][int(T)] = x
    # the per-reference block belongs to the chosen criterion only when --choose was given; else to the best one
    nuc = {}
    sec = re.search(rf"criterion \({re.escape(rc)}, {re.escape(thr)}, {re.escape(nmin)}\):\n((?:\s+suggested.*\n)+)",
                    text)
    if sec:
        nuc = {int(T): n for T, n in re.findall(r"at (\d+) K: (\d+)", sec[1])}
    if not (xc and glass and nuc):
        sys.exit(f"{d}/calibrate.out: missing per-reference fractions or the --nucleated-size block for "
                 f"criterion ({rc}, {thr}, {nmin}); rerun calibrate.py with --choose {rc} {thr} {nmin}")
    ts = sorted(nuc)
    for name, tab in (("crystal", xc), ("amorphous", glass)):
        for cell, row in tab.items():
            if sorted(row) != ts:
                sys.exit(f"{d}/calibrate.out: {name} {cell} has temperatures {sorted(row)}, expected {ts}")

    arr = lambda vals: "( " + " ".join(f"[{T}]={v}" for T, v in sorted(vals.items())) + " )"
    out = [f"# Generated by recryst/calib/make_params.py from {d.name}/calibrate.out -- do not edit; rerun",
           "# submit_calibrate.sh (or make_params.py) after a new calibration. Sourced by params/<MODEL_ID>.sh.",
           f"# Criterion source: {'calibrate.py --choose' if chosen else 'calibrate.py best (no --choose given)'}.",
           f"Q_RC={rc}; Q_THR={thr}; Q_NMIN={nmin}",
           f'Q_VARS="-var q_rc {rc} -var q_thr {thr} -var q_nmin {nmin}"      # LAMMPS (in.anneal, in.ramp)',
           f'Q_ARGS="--q-rc {rc} --q-thr {thr} --q-nmin {nmin}"   # analysis/recryst_summary.py',
           f'CALIB_TS="{" ".join(map(str, ts))}"',
           f"declare -A NUC={arr(nuc)}            # --nucleated-size at T"]
    for cell in sorted(xc):
        out.append(f"declare -A XC_{cell}={arr(xc[cell])}       # crystal reference xfracGST at T")
    for cell in sorted(glass):
        out.append(f"declare -A GLASS_{cell}={arr(glass[cell])}    # glass xfracGST at T")
    (d / "calib_params.sh").write_text("\n".join(out) + "\n")
    print(f"wrote {d}/calib_params.sh: criterion {rc}/{thr}/{nmin}, T {ts}, crystal {sorted(xc)}, glass {sorted(glass)}")


if __name__ == "__main__":
    main()
